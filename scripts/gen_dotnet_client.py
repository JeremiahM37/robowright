"""Write the .NET client's tool classes from the MCP server's own tool list, as gen_js_client.py does for JavaScript.

    python scripts/gen_dotnet_client.py          # rewrite the generated files under clients/dotnet/Robowright/
    python scripts/gen_dotnet_client.py --check  # exit 1 if they are out of date (tests run this)

Each tool becomes an async method in Playwright for .NET's style: its required arguments are parameters, the rest an
options object with a property each (await rw.Robot.LaunchAsync(new() { Robot = "panda" })).
"""

from __future__ import annotations

import asyncio
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_js_client import _camel, _split, _tools  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "clients" / "dotnet" / "Robowright"
HEADER = "// Generated by scripts/gen_dotnet_client.py from the MCP server's tool list. Do not edit.\n"
KEYWORDS = set(
    "abstract as base bool break byte case catch char checked class const continue decimal default delegate do double "
    "else enum event explicit extern false finally fixed float for foreach goto if implicit in int interface internal "
    "is lock long namespace new null object operator out override params private protected public readonly ref return "
    "sbyte sealed short sizeof stackalloc static string struct switch this throw true try typeof uint ulong unchecked "
    "unsafe ushort using virtual void volatile while".split()
)


def _pascal(name: str) -> str:
    c = _camel(name)
    return c[:1].upper() + c[1:]


def _ident(name: str) -> str:
    c = _camel(name)
    return "@" + c if c in KEYWORDS else c


def _cs_type(schema: dict) -> str:
    """The type a required parameter takes; an options property is the same, made nullable."""
    if "anyOf" in schema:
        parts = [s for s in schema["anyOf"] if s.get("type") != "null"]
        return _cs_type(parts[0]) if len(parts) == 1 else "object"
    t = schema.get("type")
    if t == "string":
        return "string"
    if t == "number":
        return "double"
    if t == "integer":
        return "int"
    if t == "boolean":
        return "bool"
    if t == "array":
        return "IEnumerable<double>" if schema.get("items", {}).get("type") == "number" else "IEnumerable<object>"
    if t == "object":
        return "IDictionary<string, object?>"
    return "object"


def _doc(text: str, indent: str) -> str:
    lines = [ln.strip() for ln in (text or "").strip().splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    esc = [ln.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") for ln in lines]
    return f"{indent}/// <summary>\n" + "".join(f"{indent}/// {ln}".rstrip() + "\n" for ln in esc) + f"{indent}/// </summary>\n"


def render(tools: list[dict]) -> dict[str, str]:
    tools = sorted(tools, key=lambda t: t["name"])
    spaces: dict[str, list[str]] = {}
    options: dict[str, list[str]] = {}
    for t in tools:
        ns, camel = _split(t["name"])
        method = camel[:1].upper() + camel[1:] + "Async"
        schema = t["inputSchema"]
        props, req = schema.get("properties", {}), schema.get("required", [])
        opt = [k for k in props if k not in req]
        cls = ns.capitalize() + camel[:1].upper() + camel[1:] + "Options"
        params = [f"{_cs_type(props[k])} {_ident(k)}" for k in req]
        if opt:
            params.append(f"{cls}? options = null")
        puts = "".join(f'        args["{k}"] = {_ident(k)};\n' for k in req)
        spaces.setdefault(ns, []).append(
            _doc(t.get("description", ""), "    ")
            + f"    public Task<string> {method}({', '.join(params)})\n    {{\n"
            + "        var args = new Dictionary<string, object?>();\n"
            + puts
            + ("        options?.AddTo(args);\n" if opt else "")
            + f'        return _rw.CallAsync("{t["name"]}", args);\n    }}\n'
        )
        if opt:
            fields = "".join(f"    public {_cs_type(props[k])}? {_pascal(k)} {{ get; set; }}\n\n" for k in opt)
            adds = "".join(f'        if ({_pascal(k)} != null) args["{k}"] = {_pascal(k)};\n' for k in opt)
            options.setdefault(ns, []).append(
                f'/// <summary>Options for <see cref="{ns.capitalize()}Tools.{method}"/>.</summary>\n'
                f"public sealed class {cls}\n{{\n{fields}"
                f"    internal void AddTo(Dictionary<string, object?> args)\n    {{\n{adds}    }}\n}}\n"
            )

    using = "using System.Collections.Generic;\nusing System.Threading.Tasks;\n\nnamespace Robowright;\n\n"
    files = {}
    for ns, methods in spaces.items():
        cls = ns.capitalize() + "Tools"
        files[f"{cls}.g.cs"] = (
            HEADER
            + "#nullable enable\n"
            + using
            + f"/// <summary>The {ns}_ tools of the robowright MCP server.</summary>\n"
            + f"public sealed class {cls}\n{{\n    private readonly RobowrightClient _rw;\n\n"
            + f"    internal {cls}(RobowrightClient rw) => _rw = rw;\n\n"
            + "\n".join(methods)
            + "}\n\n"
            + "\n".join(options.get(ns, []))
        )

    expect = next(t for t in tools if t["name"] == "robot_expect")["description"]
    matchers = sorted(set(re.findall(r"\b(to_(?:be|have)_[a-z_]+)\b", expect)))
    ms = "\n".join(
        f"    public Task<string> {_pascal(m)}Async(object? arg = null, IDictionary<string, object?>? args = null) =>\n"
        f'        _rw.ExpectCallAsync(_subject, "{m}", arg, args, _timeout, _negate);\n'
        for m in matchers
    )
    files["Assertions.g.cs"] = (
        HEADER
        + "#nullable enable\n"
        + using
        + "/// <summary>\n/// Playwright-style assertions: each returns the PASS line, or throws ExpectationException with the reason.\n"
        + '/// The first argument is the matcher\'s main one (ToBeInsideAsync("bin")) or a dictionary of its arguments;\n'
        + "/// the second, a dictionary of the rest.\n/// </summary>\n"
        + "public sealed class Assertions\n{\n    private readonly RobowrightClient _rw;\n    private readonly string _subject;\n"
        + "    private readonly double? _timeout;\n    private readonly bool _negate;\n\n"
        + "    internal Assertions(RobowrightClient rw, string subject, double? timeout, bool negate)\n    {\n"
        + "        _rw = rw;\n        _subject = subject;\n        _timeout = timeout;\n        _negate = negate;\n    }\n\n"
        + "    /// <summary>The same matchers, expecting the opposite.</summary>\n"
        + "    public Assertions Not => new(_rw, _subject, _timeout, !_negate);\n\n"
        + ms
        + "}\n"
    )
    return files


def main() -> int:
    files = render(asyncio.run(_tools()))
    targets = {SRC / name: text for name, text in files.items()}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("out of date (run python scripts/gen_dotnet_client.py): " + ", ".join(stale))
            return 1
        return 0
    SRC.mkdir(parents=True, exist_ok=True)
    for p, text in targets.items():
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
