"""Write the JavaScript client's tool table and its TypeScript types from the MCP server's own tool list.

    python scripts/gen_js_client.py          # rewrite clients/js/src/tools.js and clients/js/index.d.ts
    python scripts/gen_js_client.py --check  # exit 1 if they are out of date (tests run this)

The server is the one source of truth: a tool added, renamed or given a new argument there reaches the
JavaScript client by running this, and a test fails until someone does.
"""

from __future__ import annotations

import asyncio
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JS = ROOT / "clients" / "js"
PREFIXES = ("robot_", "ros2_", "sim_")


async def _tools() -> list[dict]:
    from mcp import Client

    from robowright.mcp_server import build_server

    async with Client(build_server()) as c:
        tools = await c.list_tools()
    return [t.model_dump(mode="json", by_alias=True) for t in getattr(tools, "tools", tools)]


def _camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def _ts_type(schema: dict) -> str:
    if "anyOf" in schema:
        parts = [_ts_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " | ".join(dict.fromkeys(parts)) or "unknown"
    t = schema.get("type")
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "array":
        return f"Array<{_ts_type(schema.get('items', {}))}>"
    if t == "object":
        return "Record<string, unknown>"
    return "unknown"


def _split(name: str) -> tuple[str, str]:
    for p in PREFIXES:
        if name.startswith(p):
            return p[:-1], _camel(name[len(p) :])
    raise ValueError(f"tool {name!r} has no robot_, ros2_ or sim_ prefix")


def _doc(text: str, indent: str) -> str:
    lines = [ln.strip() for ln in (text or "").strip().splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    body = "\n".join(f"{indent} * {ln}".rstrip() for ln in lines).replace("*/", "* /")
    return f"{indent}/**\n{body}\n{indent} */\n"


def render(tools: list[dict]) -> tuple[str, str]:
    tools = sorted(tools, key=lambda t: t["name"])
    table = []
    for t in tools:
        ns, method = _split(t["name"])
        props = t["inputSchema"].get("properties", {})
        table.append({"tool": t["name"], "ns": ns, "method": method, "params": list(props)})
    js = (
        "// Generated by scripts/gen_js_client.py from the MCP server's tool list. Do not edit.\n"
        f"export const TOOLS = {json.dumps(table, indent=2)};\n"
    )

    spaces: dict[str, list[str]] = {}
    for t in tools:
        ns, method = _split(t["name"])
        schema = t["inputSchema"]
        props, req = schema.get("properties", {}), set(schema.get("required", []))
        fields = "".join(f"    {k}{'' if k in req else '?'}: {_ts_type(v)}{'' if k in req else ' | null'};\n" for k, v in props.items())
        opt = "" if req else "?"
        arg = f"args{opt}: {{\n{fields}  }}" if props else ""
        spaces.setdefault(ns, []).append(_doc(t.get("description", ""), "  ") + f"  {method}({arg}): Promise<string>;\n")

    matchers = sorted(
        set(re.findall(r"\b(to_(?:be|have)_[a-z_]+)\b", next(t for t in tools if t["name"] == "robot_expect")["description"]))
    )
    mlines = "".join(
        f"  {_camel(m)}(arg?: unknown, options?: Record<string, unknown> & {{ timeout?: number }}): Promise<string>;\n" for m in matchers
    )
    ifaces = "".join(f"export interface {ns.capitalize()}Tools {{\n{''.join(spaces[ns])}}}\n\n" for ns in sorted(spaces))
    dts = f"""// Generated by scripts/gen_js_client.py from the MCP server's tool list. Do not edit.

{ifaces}export interface Assertions {{
{mlines}  /** The same matchers, expecting the opposite. */
  readonly not: Assertions;
}}

export interface LaunchOptions {{
  /** The command that starts the server; default ["robowright", "mcp"] (or ROBOWRIGHT_COMMAND, split on spaces). */
  command?: string[];
  /** Environment for the server process (default: this process's). */
  env?: Record<string, string | undefined>;
  /** Working directory for the server process. */
  cwd?: string;
  /** Where the server's stderr goes: "inherit" (default) or "ignore". */
  stderr?: "inherit" | "ignore";
}}

export class RobowrightError extends Error {{
  /** The tool that failed, e.g. "robot_pick". */
  readonly tool: string;
}}

/** An expectation that did not hold (robot_expect returned FAIL). */
export class ExpectationError extends Error {{
  readonly tool: string;
}}

export class Robowright {{
  readonly robot: RobotTools;
  readonly ros2: Ros2Tools;
  readonly sim: SimTools;
  /** Playwright-style assertions; a failing one throws ExpectationError. */
  expect(subject: string, options?: {{ timeout?: number }}): Assertions;
  /** Call any tool by its MCP name, e.g. call("robot_pick", {{ object: "cube" }}). */
  call(tool: string, args?: Record<string, unknown>): Promise<string>;
  /** Stop the server (closing its worlds). */
  close(): Promise<void>;
  /** The server's name and version. */
  readonly server: {{ name: string; version: string }};
}}

/** Start the robowright MCP server and connect to it. */
export function launch(options?: LaunchOptions): Promise<Robowright>;
"""
    return js, dts


def main() -> int:
    js, dts = render(asyncio.run(_tools()))
    targets = {JS / "src" / "tools.js": js, JS / "index.d.ts": dts}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("out of date (run python scripts/gen_js_client.py): " + ", ".join(stale))
            return 1
        return 0
    for p, text in targets.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
