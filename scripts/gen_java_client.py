"""Write the Java client's tool classes from the MCP server's own tool list, as gen_js_client.py does for JavaScript.

    python scripts/gen_java_client.py          # rewrite the generated files under clients/java/src/robowright/
    python scripts/gen_java_client.py --check  # exit 1 if they are out of date (tests run this)

Each tool becomes a method: its required arguments are parameters, the rest an Options object with a setter each,
the way Playwright for Java writes page.click(selector, new Page.ClickOptions().setTimeout(500)).
"""

from __future__ import annotations

import asyncio
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_js_client import _camel, _split, _tools  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "clients" / "java" / "src" / "robowright"
HEADER = "// Generated by scripts/gen_java_client.py from the MCP server's tool list. Do not edit.\n"
# Names Java will not take as methods, or that would overload Object's own (rw.robot().wait(1) would call Object.wait(long)).
RENAME = {"switch": "switchTo", "wait": "waitSeconds"}
RESERVED = {"wait", "notify", "notifyAll", "getClass", "hashCode", "equals", "toString", "clone", "finalize"} | set(
    "abstract assert boolean break byte case catch char class const continue default do double else enum extends final "
    "finally float for goto if implements import instanceof int interface long native new package private protected "
    "public return short static strictfp super switch synchronized this throw throws transient try void volatile while".split()
)


def _java_type(schema: dict) -> str:
    """The parameter type a setter or required argument takes."""
    if "anyOf" in schema:
        parts = [s for s in schema["anyOf"] if s.get("type") != "null"]
        return _java_type(parts[0]) if len(parts) == 1 else "Object"
    t = schema.get("type")
    if t == "string":
        return "String"
    if t == "number":
        return "double"
    if t == "integer":
        return "int"
    if t == "boolean":
        return "boolean"
    if t == "array":
        item = schema.get("items", {}).get("type")
        return "List<? extends Number>" if item == "number" else "List<?>"
    if t == "object":
        return "Map<String, ?>"
    return "Object"


def _javadoc(text: str, indent: str) -> str:
    lines = [ln.strip() for ln in (text or "").strip().splitlines()]
    while lines and not lines[-1]:
        lines.pop()
    esc = [ln.replace("*/", "* /").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;") for ln in lines]
    body = "\n".join(f"{indent} * {ln}".rstrip() for ln in esc)
    return f"{indent}/**\n{body}\n{indent} */\n"


def _method(name: str) -> str:
    m = RENAME.get(name, name)
    if m in RESERVED:
        raise ValueError(f"{name!r} is a Java keyword or an Object method: add it to RENAME")
    return m


def _ident(name: str) -> str:
    c = _camel(name)
    return c + "_" if c in RESERVED else c


def render(tools: list[dict]) -> dict[str, str]:
    tools = sorted(tools, key=lambda t: t["name"])
    spaces: dict[str, list[str]] = {}
    for t in tools:
        ns, camel = _split(t["name"])
        method = _method(camel)
        schema = t["inputSchema"]
        props, req = schema.get("properties", {}), schema.get("required", [])
        opt = [k for k in props if k not in req]
        cls = method[:1].upper() + method[1:] + "Options"
        params = ", ".join(f"{_java_type(props[k])} {_ident(k)}" for k in req)
        puts = "".join(f'    args.put("{k}", {_ident(k)});\n' for k in req)
        doc = _javadoc(t.get("description", ""), "  ")
        body = []
        if opt:
            sep = ", " if params else ""
            names = ", ".join(_ident(k) for k in req)
            body.append(doc + f"  public String {method}({params}) {{\n    return {method}({names}{sep}null);\n  }}\n")
            body.append(
                doc + f"  public String {method}({params}{sep}{cls} options) {{\n"
                "    Map<String, Object> args = new LinkedHashMap<>();\n"
                f"{puts}"
                "    if (options != null) args.putAll(options.values);\n"
                f'    return rw.call("{t["name"]}", args);\n  }}\n'
            )
            setters = "".join(
                f"    public {cls} set{_camel(k)[:1].upper() + _camel(k)[1:]}({_java_type(props[k])} value) {{\n"
                f'      values.put("{k}", value);\n      return this;\n    }}\n'
                for k in opt
            )
            body.append(
                f"  public static final class {cls} {{\n    final Map<String, Object> values = new LinkedHashMap<>();\n\n{setters}  }}\n"
            )
        else:
            body.append(
                doc + f"  public String {method}({params}) {{\n"
                "    Map<String, Object> args = new LinkedHashMap<>();\n"
                f"{puts}"
                f'    return rw.call("{t["name"]}", args);\n  }}\n'
            )
        spaces.setdefault(ns, []).append("\n".join(body))

    files = {}
    for ns, methods in spaces.items():
        cls = ns.capitalize() + "Tools"
        files[f"{cls}.java"] = (
            HEADER
            + "package robowright;\n\nimport java.util.LinkedHashMap;\nimport java.util.List;\nimport java.util.Map;\n\n"
            + f"/** The {ns}_ tools of the robowright MCP server. */\n"
            + f"public final class {cls} {{\n  private final Robowright rw;\n\n  {cls}(Robowright rw) {{\n    this.rw = rw;\n  }}\n\n"
            + "\n".join(methods)
            + "}\n"
        )

    expect = next(t for t in tools if t["name"] == "robot_expect")["description"]
    matchers = sorted(set(re.findall(r"\b(to_(?:be|have)_[a-z_]+)\b", expect)))
    ms = "".join(
        f'  public String {_camel(m)}() {{\n    return match("{m}", null, null);\n  }}\n\n'
        f'  public String {_camel(m)}(Object arg) {{\n    return match("{m}", arg, null);\n  }}\n\n'
        f'  public String {_camel(m)}(Object arg, Map<String, ?> args) {{\n    return match("{m}", arg, args);\n  }}\n\n'
        for m in matchers
    )
    files["Assertions.java"] = (
        HEADER
        + "package robowright;\n\nimport java.util.Map;\n\n"
        + "/**\n * Playwright-style assertions: each returns the PASS line, or throws ExpectationException with the reason.\n"
        + ' * The first argument is the matcher\'s main one (toBeInside("bin")) or a map of its arguments; the second, a map\n'
        + ' * of the rest ({@code Map.of("min_fraction", 0.5)}).\n */\n'
        + "public final class Assertions {\n  private final Robowright rw;\n  private final String subject;\n"
        + "  private final Double timeout;\n  private final boolean negate;\n\n"
        + "  Assertions(Robowright rw, String subject, Double timeout, boolean negate) {\n"
        + "    this.rw = rw;\n    this.subject = subject;\n    this.timeout = timeout;\n    this.negate = negate;\n  }\n\n"
        + "  /** The same matchers, expecting the opposite. */\n"
        + "  public Assertions not() {\n    return new Assertions(rw, subject, timeout, !negate);\n  }\n\n"
        + "  private String match(String matcher, Object arg, Map<String, ?> args) {\n"
        + "    return rw.expectCall(subject, matcher, arg, args, timeout, negate);\n  }\n\n"
        + ms.rstrip("\n")
        + "\n}\n"
    )
    return files


def main() -> int:
    files = render(asyncio.run(_tools()))
    targets = {SRC / name: text for name, text in files.items()}
    if "--check" in sys.argv:
        stale = [str(p.relative_to(ROOT)) for p, text in targets.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("out of date (run python scripts/gen_java_client.py): " + ", ".join(stale))
            return 1
        return 0
    SRC.mkdir(parents=True, exist_ok=True)
    for p, text in targets.items():
        p.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
